// bun run gen:parts
//
// Writes two files in parts/ from the shadcn M3E components (packages/m3e/src/components):
//
//   components.generated.ts  every module as a namespace import, so a part can name a
//                            component as a string ("Button") and the canvas can draw it
//   files.generated.ts       which module each exported component name comes from, read
//                            off the source, so printing code and writing the prompt do
//                            not have to load a single component
//
// Providers, the ripple and the icon internals are left out: parts never place them.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "..", "..", "packages", "m3e", "src", "components");
const parts = join(here, "..", "parts");

const SKIP = new Set(["color-mode-provider", "m3-theme-provider", "m3e-provider", "ripple", "symbols"]);
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".tsx"))
  .map((f) => f.slice(0, -4))
  .filter((f) => !SKIP.has(f))
  .toSorted();
const id = (f) => "m_" + f.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

writeFileSync(
  join(parts, "components.generated.ts"),
  [
    "// Generated by scripts/gen-parts-components.mjs (bun run gen:parts). Do not edit.",
    ...files.map((f) => `import * as ${id(f)} from "@/components/m3e/${f}";`),
    "",
    "/** every shadcn M3E module a part may use, by its file name (also its registry item name) */",
    "export const MODULES: Record<string, Record<string, unknown>> = {",
    ...files.map((f) => `  ${JSON.stringify(f)}: ${id(f)},`),
    "};",
    "",
  ].join("\n"),
);

/** the PascalCase names a module exports (and the snackbar's `toast`) */
function exportsOf(file) {
  const src = readFileSync(join(dir, `${file}.tsx`), "utf8");
  const names = new Set();
  for (const m of src.matchAll(/export\s+(?:async\s+)?(?:function|const|class)\s+([A-Za-z_$][\w$]*)/g)) names.add(m[1]);
  for (const m of src.matchAll(/export\s*\{([^}]*)\}/g))
    for (const part of m[1].split(",")) {
      const name = part.trim().split(/\s+as\s+/).pop()?.trim();
      if (name) names.add(name);
    }
  return [...names].filter((n) => /^[A-Z]/.test(n) || n === "toast");
}

const fileOf = {};
for (const f of files) for (const n of exportsOf(f)) if (!(n in fileOf)) fileOf[n] = f;
writeFileSync(
  join(parts, "files.generated.ts"),
  [
    "// Generated by scripts/gen-parts-components.mjs (bun run gen:parts). Do not edit.",
    "/** a component name -> the module file it is exported from (also its registry item name) */",
    "export const FILE_OF: Record<string, string> = {",
    ...Object.entries(fileOf)
      .toSorted(([a], [b]) => a.localeCompare(b))
      .map(([n, f]) => `  ${JSON.stringify(n)}: ${JSON.stringify(f)},`),
    "};",
    "",
  ].join("\n"),
);
console.log(`wrote parts/components.generated.ts (${files.length} modules) and parts/files.generated.ts (${Object.keys(fileOf).length} names)`);
